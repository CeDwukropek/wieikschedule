const blocks = payloads.filter(p => p.db === 'block');
const database = payloads.filter(p => Array.isArray(p.events) && Array.isArray(p.referenced));
assert(schedule.length === 1 && blocks.length === 1 && database.length === 1, 'Expected two source snapshots and one database export');
const plan = createNightlyPlan(transformSnapshots(schedule[0], blocks[0]), database[0].events, database[0].referenced);
